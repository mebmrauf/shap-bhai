const stored = () => { try { return localStorage.getItem('snake-arena.v2.lang'); } catch { return null; } };
let language = stored() === 'en' ? 'en' : 'bn';
const digits = n => String(n).replace(/\d/g, d => '০১২৩৪৫৬৭৮৯'[d]);
export const lang = () => language;
export const num = n => language === 'bn' ? digits(n) : String(n);
export function t(text, values = {}) {
  const template = language === 'bn' ? BANGLA[text] ?? text : text;
  return template.replace(/\{(\w+)\}/g, (_, name) => typeof values[name] === 'number' ? num(values[name]) : String(values[name] ?? ''));
}
export const translationKeys = () => Object.keys(BANGLA);
let staticText = null;
// Captured once at load, while the page still holds its English source text.
function captureStatic() {
  staticText = { nodes: [], attributes: [] };
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) { const node = walker.currentNode; if (node.nodeValue.trim() && BANGLA[node.nodeValue.trim()] && !node.parentElement.closest('[data-fixed-lang]')) staticText.nodes.push([node, node.nodeValue]); }
  for (const el of document.querySelectorAll('[aria-label],[placeholder]')) for (const name of ['aria-label', 'placeholder']) { const value = el.getAttribute(name); if (value && BANGLA[value]) staticText.attributes.push([el, name, value]); }
}
export function applyLanguage(next = language) {
  staticText ??= (captureStatic(), staticText);
  language = next;
  try { localStorage.setItem('snake-arena.v2.lang', language); } catch { /* The choice just lasts for this visit. */ }
  document.documentElement.lang = language;
  for (const [node, source] of staticText.nodes) node.nodeValue = source.replace(source.trim(), t(source.trim()));
  for (const [el, name, source] of staticText.attributes) el.setAttribute(name, t(source));
}
